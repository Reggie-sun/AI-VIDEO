def main():
    jobs = []
    for name, s in SHOTS.items():
        d = D / name
        d.mkdir(parents=True, exist_ok=True)
        lines = [f"# {name} 首帧/静图候选提示词（IRIS EP01 s031–s048）", "",
                 "2026-11-24。导演方案 `pilot/s031-048/plan/index.html` 已获批「按方案做首帧预览 (Recommended)」（logs/decisions.md 2026-11-24）。旧底图 `board/plates/` 不覆盖；候选只写本目录。工具 `motion-kit/tools/codex_plate.py`。",
                 "", s["note"], ""]
        for plate, base, refs, prompt in s["plates"]:
            lines += [f"## {plate}", "",
                      f"- 编辑底图（--edit-base）：`{base}`" if base else "- 编辑底图：无（新构图）" if plate != "P032PALM" else "- 编辑底图：P032 推荐件（见 runs.md）",
                      "- 参考（--ref）：" + ("、".join(f"`{r}`" for r in refs) if refs else "无"), "",
                      "```prompt", prompt, "```", ""]
            jobs.append({"shot": name, "plate": plate, "base": base, "refs": refs})
        (d / "prompt.md").write_text("\n".join(lines), encoding="utf-8")
    (Path("/tmp/s031pv") / "jobs.json").write_text(json.dumps(jobs, ensure_ascii=False, indent=1))
    print(len(SHOTS), "shots,", len(jobs), "plates")


if __name__ == "__main__":
    main()
