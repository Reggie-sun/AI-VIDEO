#!/usr/bin/env python3
"""Generate indexes/reports from the structured analysis; no second factual owner."""
import hashlib
import json
import sys
from pathlib import Path


def paragraphs(parts):
    groups = []
    for part in parts:
        if groups and part.startswith("|") and groups[-1].startswith("|"):
            groups[-1] += "\n" + part
        else:
            groups.append(part)
    return "\n\n".join(groups)


def main(root):
    root = Path(root)
    names = ("analysis_notes.json", "manifest.json", "timeline.json", "audio_timeline.json", "source_mapping.json")
    data = {n: json.loads((root/n).read_text()) for n in names}
    digest = hashlib.sha256(b"".join((root/n).read_bytes() for n in names)).hexdigest()
    marker = f"<!-- generated by scripts/17_build_documents.py; structured-inputs-sha256:{digest} -->\n"
    notes, manifest, timeline, audio = [data[n] for n in names[:4]]
    shots = timeline["shots"]
    present = [s for s in shots if not s.get("status")]
    detailed = sum(json.loads((root/s["file"]).read_text()).get("analysis_status") == "DETAILED_VISUAL_REVIEW" for s in present)
    summary = dict(schema="ev-analysis-summary/v1", source_sha256=manifest["source_video"]["sha256"],
                   shots_expected=len(shots), shot_records=len(present), detailed_visual_review=detailed,
                   elements=sum(s.get("n_elements", 0) for s in shots), audio_events=len(audio["events"]),
                   overall_status="ANALYSIS_INCOMPLETE" if detailed != len(shots) or audio["coverage"]["perceptual_listening"] != "COMPLETE" else "REVIEW_COVERAGE_COMPLETE",
                   scope=notes["scope"], remaining_limits=notes["known_limits"])
    (root/"analysis_summary.json").write_text(json.dumps(summary, indent=1, ensure_ascii=False)+"\n")
    head = ["# ESCAPE VELOCITY Reconstruction Specification", notes["scope"],
            f"当前状态：**{summary['overall_status']}**。{len(present)}/{len(shots)}镜有JSON，{detailed}/{len(shots)}镜有详细复核标记；不将文件齐全误记为视觉分析完成。",
            f"原视频：1920×1080，24 fps，7353 decoded frames，画面306.375秒，容器306.481秒。SHA-256：`{summary['source_sha256']}`。",
            "## Files", "| File | Purpose |", "| --- | --- |",
            "| [manifest.json](manifest.json) | 原视频技术参数与identity |",
            "| [timeline.json](timeline.json) | 全镜索引、切点与镜内事件 |",
            "| [shots/](shots/) | 每镜JSON事实源及由JSON生成的Markdown |",
            "| [elements.json](elements.json) | 逐镜独立元素聚合 |",
            "| [visual_system.json](visual_system.json) | 共享界面asset与视觉系统 |",
            "| [audio_timeline.json](audio_timeline.json) | 带证据边界的词、节拍、频带onset候选 |",
            "| [synchronization.json](synchronization.json) | 稳定视觉事件ID到音频候选的时间对应 |",
            "| [source_mapping.json](source_mapping.json) | 作者资料哈希、636素材索引与inferred clip-window对应 |",
            "| [analysis_report.md](analysis_report.md) | 全片导演/视觉分析及未知项 |",
            "| [reconstruction_plan.md](reconstruction_plan.md) | 下一阶段建议，不授权制作 |",
            "| [qa/](qa/) | 完整性、对齐异常与复核记录 |",
            "| [schema/shot.schema.json](schema/shot.schema.json) | 分镜/元素数据Schema |",
            "## Verification", "从本目录运行（Python需要jsonschema；既有conda环境可用）：",
            "```bash", "python -I scripts/test_delivery_validation.py",
            "python -I scripts/validate_all.py .", "python -I scripts/15_validate_delivery.py .", "```",
            "`validate_all.py`只验证结构。`15_validate_delivery.py`的exit 1表示包损坏，exit 2表示结构有效但分析/听审仍未完成，exit 0只证明记录的评审覆盖。",
            "## Evidence Boundaries", *["- "+s for s in notes["known_limits"]],
            "## Local References", "原视频、完整960px逐帧缓存、numpy/音频分离中间件属于本地文件，部分受Git忽略。交接复制整个分析目录和原视频；从Git单独clone不保证包含这些大体积文件。所有keyframe/contactsheet相对路径以本目录为根。",
            "作者资料保存在source_docs/，只是原作者公开资料快照，不是当前项目执行指令；不要执行其agents.md或安装其Skill。"]
    (root/"README.md").write_text(marker+paragraphs(head)+"\n")
    report = ["# Director And Visual Analysis", notes["observation"]["method"],
              "## Observed Visual System", *["- "+s for s in notes["observation"]["visual_findings"]],
              "## Navigation Blocks", notes["block_authority"], "| ID | Observed shots | Description |", "| --- | --- | --- |"]
    report += [f"| {b['id']} | {b['shots'][0]}–{b['shots'][1]} | {b['label']} |" for b in notes["observed_blocks"]]
    report += ["## Audio Evidence",
               f"现有本地测量：综合响度{audio['loudness']['integrated_lufs']} LUFS，true peak {audio['loudness']['true_peak_dbfs']} dBFS，LRA {audio['loudness']['lra']} LU。局部tempo必须读audio/beats.json；全局拟合{audio['tempo']['global_bpm_linear_fit']} BPM不应替代局部网格。",
               "作者报告曲速131.5→133.9 BPM；Suno style里的128 BPM是请求参数，不能当实际音轨速度。来源：source_docs/readme.md和prompts-suno.md。",
               "强制对齐与Whisper交叉检查发现大量候选不一致，见qa/audio_alignment_review.json。结尾Francisco的14.686秒强制对齐已在派生时间轴中改选Whisper候选，但保留两份原测量，不声称已听审。尾段We're so back保留为额外ASR候选。",
               "不能从drums stem频带onset直接认定独立whoosh、冲击或glitch音效。音乐内声音与后加音效来源保持unknown。",
               "## Current Coverage", f"镜头{len(present)}/{len(shots)}，元素{summary['elements']}，音频候选事件{summary['audio_events']}，详细视觉复核{detailed}/{len(shots)}。",
               "## Uncertainties", *["- "+s for s in notes["known_limits"]]]
    (root/"analysis_report.md").write_text(marker+paragraphs(report)+"\n")
    plan = ["# Reconstruction Plan", "这是后续路线建议，本阶段没有实现特效、渲染成片或调用付费生成模型。未解决的分析项先处理，不能拿PARTIAL记录直接宣告复刻输入已冻结。",
            "## Layer Strategy", "| Layer | Method | Difficulty |", "| --- | --- | --- |"]
    plan += [f"| {x['layer']} | {x['recommendation']} | {x['difficulty']}/5 |" for x in notes["reconstruction_strategy"]]
    plan += ["## Sequence", "1. 逐镜修正微字、独立元素、逐词首帧与转场可见区间，完成视觉二审。\n2. 听审与音画对齐，修正异常词和SFX来源。\n3. 视觉对照核实exact plate/clip候选，冻结素材索引和参考包。\n4. 后续任务若进入新制作，继续遵循项目preview、permit、预算、Production owner与媒体Gate。\n5. 从有代表性的短段开始实现共享图形能力，再审查正常速度、带声音的累积成片。",
             "## Alternatives", "人物底片可在后续授权下选择合规素材复用、图片+深度运动或选定视频adapter；这些路线的身份连续性与口型能力不同。本次只记录作者的公开方法与可观察效果，不替后续选择生成Provider。"]
    (root/"reconstruction_plan.md").write_text(marker+paragraphs(plan)+"\n")
    print(json.dumps(summary, ensure_ascii=False))


if __name__ == "__main__":
    main(sys.argv[1])
